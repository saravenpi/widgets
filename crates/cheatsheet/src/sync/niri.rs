//! Niri keybindings generator.

use crate::model::{Category, Keybind, KeybindConfig};

pub fn generate_niri(config: &KeybindConfig) -> String {
    let mut out = String::new();
    out.push_str("// Generated by widgets cheatsheet sync. Do not edit directly.\n");
    out.push_str("binds {\n");

    for cat in &config.categories {
        format_category(&mut out, cat, &config.terminal);
    }
    out.push_str("}\n");
    out
}

fn format_category(out: &mut String, cat: &Category, terminal: &str) {
    out.push_str(&format!("    // --- {} ---\n", cat.name));
    for b in &cat.binds {
        format_bind(out, b, terminal);
    }
}

fn format_bind(out: &mut String, b: &Keybind, terminal: &str) {
    if b.key == "1..9" {
        format_workspaces(out, false);
        return;
    }
    if b.key == "Shift+1..9" {
        format_workspaces(out, true);
        return;
    }

    let key_combo = if b.key.starts_with("XF86") {
        b.key.clone()
    } else {
        format!("Mod+{}", b.key)
    };

    if let Some(ref ni) = b.niri {
        out.push_str(&format!("    {key_combo} {{ {ni}; }}\n"));
    } else if let Some(ref ex) = b.exec {
        let cmd = ex.replace("$terminal", terminal);
        out.push_str(&format!("    {key_combo} {{ spawn \"sh\" \"-c\" \"{cmd}\"; }}\n"));
    } else if let Some(ref act) = b.action {
        if let Some(cmd) = action_command(act) {
            out.push_str(&format!("    {key_combo} {{ {cmd}; }}\n"));
        }
    }
}

fn format_workspaces(out: &mut String, shifted: bool) {
    for i in 1..=9 {
        if shifted {
            out.push_str(&format!("    Mod+Shift+{i} {{ move-column-to-workspace {i}; }}\n"));
        } else {
            out.push_str(&format!("    Mod+{i} {{ focus-workspace {i}; }}\n"));
        }
    }
    if shifted {
        out.push_str("    Mod+Shift+0 { move-column-to-workspace 10; }\n");
    } else {
        out.push_str("    Mod+0 { focus-workspace 10; }\n");
    }
}

fn action_command(action: &str) -> Option<&'static str> {
    match action {
        "close" => Some("close-window"),
        "fullscreen" => Some("fullscreen-window"),
        "focus_left" => Some("focus-column-left"),
        "focus_down" => Some("focus-window-down"),
        "focus_up" => Some("focus-window-up"),
        "focus_right" => Some("focus-column-right"),
        "move_left" => Some("move-column-left"),
        "move_down" => Some("move-window-down"),
        "move_up" => Some("move-window-up"),
        "move_right" => Some("move-column-right"),
        _ => None,
    }
}
