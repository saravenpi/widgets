//! Sway keybindings generator.

use crate::model::{Category, Keybind, KeybindConfig};

pub fn generate_sway(config: &KeybindConfig) -> String {
    let mut out = String::new();
    out.push_str("# Generated by widgets cheatsheet sync. Do not edit directly.\n");
    out.push_str(&format!("set $mod {}\n", config.mod_key));
    out.push_str(&format!("set $term {}\n\n", config.terminal));

    for cat in &config.categories {
        format_category(&mut out, cat);
    }
    out
}

fn format_category(out: &mut String, cat: &Category) {
    out.push_str(&format!("# --- {} ---\n", cat.name));
    for b in &cat.binds {
        format_bind(out, b);
    }
    out.push('\n');
}

fn format_bind(out: &mut String, b: &Keybind) {
    if b.key == "1..9" {
        format_workspaces(out, false);
        return;
    }
    if b.key == "Shift+1..9" {
        format_workspaces(out, true);
        return;
    }

    let key_spec = if b.key.starts_with("XF86") {
        b.key.clone()
    } else {
        format!("$mod+{}", b.key)
    };

    if let Some(ref sw) = b.sway {
        out.push_str(&format!("bindsym {key_spec} {sw}\n"));
    } else if let Some(ref ex) = b.exec {
        let cmd = ex.replace("$terminal", "$term");
        out.push_str(&format!("bindsym {key_spec} exec {cmd}\n"));
    } else if let Some(ref act) = b.action {
        if let Some(cmd) = action_command(act) {
            out.push_str(&format!("bindsym {key_spec} {cmd}\n"));
        }
    }
}

fn format_workspaces(out: &mut String, shifted: bool) {
    for i in 1..=9 {
        if shifted {
            out.push_str(&format!(
                "bindsym $mod+Shift+{i} move container to workspace number {i}; workspace number {i}\n"
            ));
        } else {
            out.push_str(&format!("bindsym $mod+{i} workspace number {i}\n"));
        }
    }
    if shifted {
        out.push_str("bindsym $mod+Shift+0 move container to workspace number 10; workspace number 10\n");
    } else {
        out.push_str("bindsym $mod+0 workspace number 10\n");
    }
}

fn action_command(action: &str) -> Option<&'static str> {
    match action {
        "close" => Some("kill"),
        "fullscreen" => Some("fullscreen toggle"),
        "reload" => Some("reload"),
        "focus_left" => Some("focus left"),
        "focus_down" => Some("focus down"),
        "focus_up" => Some("focus up"),
        "focus_right" => Some("focus right"),
        "move_left" => Some("move left"),
        "move_down" => Some("move down"),
        "move_up" => Some("move up"),
        "move_right" => Some("move right"),
        _ => None,
    }
}
