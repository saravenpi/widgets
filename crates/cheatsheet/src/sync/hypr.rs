//! Hyprland keybindings generator.

use crate::model::{Category, Keybind, KeybindConfig};

pub fn generate_hypr(config: &KeybindConfig) -> String {
    let mut out = String::new();
    out.push_str("# Generated by widgets cheatsheet sync. Do not edit directly.\n");
    out.push_str("$mainMod = SUPER\n\n");

    for cat in &config.categories {
        format_category(&mut out, cat, &config.terminal);
    }
    out
}

fn format_category(out: &mut String, cat: &Category, terminal: &str) {
    out.push_str(&format!("# --- {} ---\n", cat.name));
    for b in &cat.binds {
        format_bind(out, b, terminal);
    }
    out.push('\n');
}

fn format_bind(out: &mut String, b: &Keybind, terminal: &str) {
    if b.key == "1..9" {
        format_workspaces(out, false);
        return;
    }
    if b.key == "Shift+1..9" {
        format_workspaces(out, true);
        return;
    }

    let (mods, base_key) = split_mod_and_key(&b.key);
    let hypr_key = normalize_key(base_key);

    if let Some(ref hy) = b.hypr {
        out.push_str(&format!("bind = {mods}, {hypr_key}, {hy}\n"));
    } else if let Some(ref ex) = b.exec {
        let cmd = ex.replace("$terminal", terminal);
        out.push_str(&format!("bind = {mods}, {hypr_key}, exec, {cmd}\n"));
    } else if let Some(ref act) = b.action {
        if let Some(cmd) = action_command(act) {
            out.push_str(&format!("bind = {mods}, {hypr_key}, {cmd}\n"));
        }
    }
}

fn split_mod_and_key(key: &str) -> (&'static str, &str) {
    if key.starts_with("XF86") {
        ("", key)
    } else if let Some(k) = key.strip_prefix("Shift+") {
        ("$mainMod SHIFT", k)
    } else {
        ("$mainMod", key)
    }
}

fn normalize_key(key: &str) -> &str {
    match key {
        "Return" => "RETURN",
        "space" => "SPACE",
        "question" => "SLASH",
        other => other,
    }
}

fn format_workspaces(out: &mut String, shifted: bool) {
    for i in 1..=9 {
        if shifted {
            out.push_str(&format!("bind = $mainMod SHIFT, {i}, movetoworkspace, {i}\n"));
        } else {
            out.push_str(&format!("bind = $mainMod, {i}, workspace, {i}\n"));
        }
    }
    if shifted {
        out.push_str("bind = $mainMod SHIFT, 0, movetoworkspace, 10\n");
    } else {
        out.push_str("bind = $mainMod, 0, workspace, 10\n");
    }
}

fn action_command(action: &str) -> Option<&'static str> {
    match action {
        "close" => Some("killactive"),
        "fullscreen" => Some("fullscreen, 0"),
        "reload" => Some("forcerendererreload"),
        "focus_left" => Some("movefocus, l"),
        "focus_down" => Some("movefocus, d"),
        "focus_up" => Some("movefocus, u"),
        "focus_right" => Some("movefocus, r"),
        "move_left" => Some("movewindow, l"),
        "move_down" => Some("movewindow, d"),
        "move_up" => Some("movewindow, u"),
        "move_right" => Some("movewindow, r"),
        _ => None,
    }
}
